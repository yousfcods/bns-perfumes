export function getPriceForSize(
  perfume: { price?: number; sizePrices?: Record<string, number> } | null | undefined,
  size: string,
  concentration: 'x1' | 'x2' = 'x1'
): number {
  if (!perfume) return 0;

  let basePrice = 0;
  if (perfume.sizePrices && perfume.sizePrices[size] !== undefined) {
    basePrice = perfume.sizePrices[size];
  } else {
    const ratioMap: Record<string, number> = {
      '12ml': 250,
      '15ml': 300,
      '30ml': 500,
      '50ml': 800,
      '80ml': 1200,
      '100ml': 1800,
    };
    basePrice = ratioMap[size] || perfume.price || 1800;
  }

  const multiplier = concentration === 'x2' ? 2 : 1;
  return basePrice * multiplier;
}

